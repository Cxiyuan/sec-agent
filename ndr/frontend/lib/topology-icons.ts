function dataUri(svg: string): string {
  // 用 encodeURIComponent 而不是 base64：`#` / `<` / `"` 都在这里被转义，
  // 而 base64 会要求先做 UTF-8 编码（这两份稿子目前是纯 ASCII，但以后换图标不一定）。
  return `image://data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

